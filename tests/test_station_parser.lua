package.path = "runtime/?.lua;" .. package.path
-- Own parser only, using invented/redacted client addresses. No device access.
local parse=assert(loadfile("runtime/station_parser.lua"))()
local fixture=assert(loadfile("runtime/station_fixtures.lua"))()
local cases={}
local function check(name,body,valid,count)
    local result=parse(body)
    assert(result.parsed==valid,"unexpected parsing: "..name.." ("..tostring(result.error)..")")
    if valid then assert(result.count==count,"wrong count: "..name)
    else assert(result.count==0 and next(result.macs)==nil,"partial acceptance: "..name) end
    cases[#cases+1]=name
end
local function changed(old,new)
    local body,n=fixture.main:gsub(old,new,1)
    assert(n==1,"fixture substitution missing")
    return body
end
check("empty_native_header",fixture.header,true,0)
check("actual_main_redacted_13_footer",fixture.main,true,1)
check("actual_satellite_redacted_13_footer",fixture.satellite,true,1)
check("two_complete_stations",fixture.main..fixture.main:sub(#fixture.header+1):gsub("02:00:00:00:00:01","02:00:00:00:00:02"),true,2)
check("empty_measurement_flags",changed("LM NR BRP BRA BRT", ""),true,1)
check("all_measurement_flags",changed("LM NR BRP BRA BRT", "LM NR BRP BRA BRT LCIM FTMRR"),true,1)
check("optional_classes_absent",changed(" Supported Operating classes[^\n]*\n",""),true,1)
check("optional_channels_native_frequencies",changed(" Max STA phymode", " Channels supported\t\t: 5180 5200 5220 5240\n Max STA phymode"),true,1)
check("crlf",fixture.main:gsub("\r\n","\n"):gsub("\n","\r\n"),true,1)
check("signed_snr_minimum",changed(" SNR[^\n]*", " SNR: -128"),true,1)
check("unsigned_power_maximum",changed(" Maximum Tx Power[^\n]*", " Maximum Tx Power: 255"),true,1)
check("unknown_row",fixture.main.."Injected arbitrary footer\n",false)
check("truncated_footer",changed(" Max STA phymode[^\n]*\n",""),false)
check("missing_final_newline",fixture.main:gsub("[\r\n]+$",""),false)
check("reordered_footer",changed(" Minimum Tx Power[^\n]*", " Maximum Tx Power: 0"),false)
check("unknown_flags",changed("LM NR BRP BRA BRT", "LM NR UNKNOWN"),false)
check("reordered_flags",changed("LM NR BRP BRA BRT", "NR LM"),false)
check("duplicate_flags",changed("LM NR BRP BRA BRT", "LM LM"),false)
check("snr_too_high",changed(" SNR[^\n]*", " SNR: 128"),false)
check("power_too_high",changed(" Maximum Tx Power[^\n]*", " Maximum Tx Power: 256"),false)
check("negative_unsigned_power",changed(" Minimum Tx Power[^\n]*", " Minimum Tx Power: -1"),false)
check("operating_class_too_high",changed(" Current Operating class[^\n]*", " Current Operating class: 256"),false)
check("bad_class_list",changed(" Supported Operating classes[^\n]*", " Supported Operating classes: 129 256"),false)
check("rates_7bit_bound",changed(" Supported Rates[^\n]*", " Supported Rates: 12 128"),false)
check("rate_list_bound",changed(" Supported Rates[^\n]*", " Supported Rates: "..string.rep("12 ",45)),false)
check("unknown_capability",changed(" HT Capability[^\n]*", " HT Capability: Maybe"),false)
check("unknown_band",changed(" Operating band[^\n]*", " Operating band: 60GHz"),false)
check("unknown_phymode",changed(" Max STA phymode[^\n]*", " Max STA phymode: UNKNOWN"),false)
check("malformed_frequency_list",changed(" Max STA phymode", " Channels supported: 5180 arbitrary\n Max STA phymode"),false)
check("frequency_wrong_band",changed(" Max STA phymode", " Channels supported: 2412\n Max STA phymode"),false)
check("duplicate_station",fixture.main..fixture.main:sub(#fixture.header+1),false)
check("multicast_station",fixture.main:gsub("02:00:00:00:00:01","03:00:00:00:00:01"),false)
check("control_character",fixture.main.."\0",false)
